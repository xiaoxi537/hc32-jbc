/**
 *******************************************************************************
 * @file  app_heat.h
 * @brief 加热控制：测温 → 烙铁头识别 → PID → 软件 PWM
 *
 * 整个循环由 TMRA6 的加热脉冲驱动：脉冲结束 → 断电测温 5 ms →
 * 算 PID → 写下一轮占空比。周期约 25.3 ms，和原机一致。
 *******************************************************************************
 */
#ifndef __APP_HEAT_H__
#define __APP_HEAT_H__

/** 初始化 PID 状态与 ADC 相位；必须在外设都 init 完之后调用 */
void init_heat(void);

/** 推进一轮加热状态机（内部按脉冲完成标志和 5 ms 窗口判断） */
void task_heat(void);

/** SysTick 每 1 ms 调用：把加热控制放进最高优先级，不被刷屏阻塞 */
void tick_heat(void);

#endif /* __APP_HEAT_H__ */

