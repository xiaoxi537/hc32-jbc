/**
 *******************************************************************************
 * @file  bsp_heater.h
 * @brief 加热功率级：PA10 + TMRA6 软件 PWM
 *
 * 原机方案：TMRA6 自由运行，溢出周期 ≈101 µs；一个加热脉冲 251 次溢出
 * （≈25.3 ms）。溢出中断里按占空比 0…250 逐周期翻转 PA10，脉冲结束后停
 * 定时器并置完成标志，应用层据此开始下一轮"测温 → PID"。
 *
 * 为什么不用硬件 PWM：原机就是这么做的，而且加热丝和热电偶共用同一个
 * 接口，必须在脉冲结束后留出固定窗口断电测温度，硬件 PWM 反而不好对齐。
 *******************************************************************************
 */
#ifndef __BSP_HEATER_H__
#define __BSP_HEATER_H__

#include <stdbool.h>
#include <stdint.h>

/** 初始化 PA10 与 TMRA6（溢出中断），并先跑一个空脉冲让状态确定 */
void init_heater(void);

/**
 * @brief  启动一个加热脉冲
 * @param  duty 0…250，对应 0…100%，分辨力 0.4%
 */
void start_heat_pulse(uint8_t duty);

/** 立刻关断加热并停 PWM；故障、休眠、写 Flash 前都必须先调它 */
void stop_heat_output(void);

/**
 * @brief  取走"脉冲已结束"标志
 * @retval true 本周期已结束，可以开始测温
 */
bool take_pulse_done(void);

#endif /* __BSP_HEATER_H__ */

/*******************************************************************************
 * EOF (not truncated)
 ******************************************************************************/
