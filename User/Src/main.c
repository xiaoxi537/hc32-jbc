/**
 *******************************************************************************
 * @file  main.c
 * @brief 上电引导：时钟 → 裸机时基 → 应用初始化 → 主循环
 *
 * 失败处理原则：哪一步错了就停在哪一步死循环，J-Link 看 PC 定位
 * （看门狗尚未启用，不会自动复位）。
 * 不带着错误的时钟或未初始化的显示继续跑，避免"看起来在跑、实际全错"。
 *
 * 本文件只依赖 app.h 与 bsp_clk.h，不包含厂商头文件、不碰寄存器。
 *******************************************************************************
 */
#include "app.h"
#include "bsp_clk.h"

int main(void)
{
    /* 时钟没配对，后面 SPI/ADC/加热的时序全是假的，直接停机 */
    if (!init_clock()) {
        /* 看门狗未启用：只能等人工复位；J-Link 看 PC 定位 */
        while (1) {
        }
    }

    /* 没有 1 ms 节拍，加热周期和按键消抖都无从谈起 */
    if (!init_tick(TICK_HZ)) {
        while (1) {
        }
    }

    /* 显示链路或界面没起来：此时背光还没开，屏不亮就是软件初始化失败 */
    if (!init_app()) {
        /* 看门狗未启用：只能等人工复位；PC 停在这里即初始化失败 */
        while (1) {
        }
    }

    /* 主循环永不返回：所有状态机都在 task_app 里按节拍推进 */
    for (;;) {
        task_app();
    }
}

