/**
 *******************************************************************************
 * @file  app_check.h
 * @brief 电源状态机：休眠 / 待机 / 自动关机（1 ms 节拍）
 *
 * 编码器解码不在这里：它已经移到 bsp_input.c 的 SysTick 里，
 * 因为主循环刷屏或写 Flash 时一次能停十几毫秒，放主循环会丢步。
 *******************************************************************************
 */
#ifndef __APP_CHECK_H__
#define __APP_CHECK_H__

/** 清零开关去抖历史（须在 init_inputs 之后调用） */
void init_check(void);

/** 1 ms 周期调用：联锁、在位、关机/待机/休眠计时 */
void task_check(void);

/**
 * 唤醒后抑制待机的时长上限（ms）。
 *
 * 为什么必须有上限：抑制的解除条件本来是"PA4 抬起过"，但如果用户
 * 一直把手柄压在座子上操作，PA4 永远不抬起，抑制就变成永久的 ——
 * 待机/自动关机从此失效，手柄等于一直加热，既不安全也费电。
 * 所以加一个超时兜底：即使手柄还没离开，超时后也恢复自动待机判定。
 * 60 s 足够覆盖"按键唤醒后立刻进菜单调参数"的常见操作时长。
 */
#define APP_CHECK_STANDBY_SUPPRESS_MS   (60000UL)

/**
 * @brief  告诉电源状态机"用户刚主动操作过，别急着打进待机"
 *
 * 为什么需要它：用户按着键从待机唤醒时，手柄可能还压在座子上（PA4 仍低）。
 * 若不抑制，1 ms 后 update_standby_input() 立刻把 FLAG_STANDBY 又置回去，
 * 表现是"菜单打开了，但温度显示 0℃、加热锁死"。
 *
 * 抑制会在 **PA4 真正抬起过（连续 16 ms 高电平）** 后自动解除，
 * 所以用户真把烙铁放回座子时，待机照常生效。
 */
void suppress_standby(void);

#endif /* __APP_CHECK_H__ */

