/**
 *******************************************************************************
 * @file  app.h
 * @brief 应用层入口（与具体硬件解耦）
 *
 * 本层只调用 bsp_*.h 暴露的函数，不访问寄存器，也不包含厂商头文件。
 *******************************************************************************
 */
#ifndef __APP_H__
#define __APP_H__

#include <stdbool.h>

/**
 * @brief  按固定顺序初始化显示、界面、输入与加热链路
 * @retval true 成功；false 显示链路或界面没起来
 * @note   内部顺序：LCD → SGL → 界面 → 输入 → 蜂鸣/背光 → ADC → 加热。
 *         界面失败时背光还没打开，现场"屏不亮"就能直接定位到软件初始化失败。
 */
bool init_app(void);

/**
 * @brief  主循环任务：1/5/10 ms 三个节拍 + 延迟保存设置
 * @note   加热任务不在这里，它由 SysTick 直接推进（见 tick_heat）。
 */
void task_app(void);

#endif /* __APP_H__ */

/*******************************************************************************
 * EOF (not truncated)
 ******************************************************************************/
